class PseLTae(nn.Module):
    """
    Pixel-Set encoder + Lightweight Temporal Attention Encoder sequence classifier
    """

    def __init__(
        self,
        input_dim=10,
        mlp1=[10, 32, 64],
        pooling="mean_std",
        mlp2=[128, 128],
        with_extra=True,
        extra_size=4,
        n_head=16,
        d_k=8,
        d_model=256,
        mlp3=[256, 128],
        dropout=0.2,
        T=1000,
        mlp4=[128, 64, 32],
        num_classes=20,
        max_temporal_shift=100,
    ):
        super(PseLTae, self).__init__()
        if with_extra:
            mlp2 = deepcopy(mlp2)
            mlp2[0] += extra_size

        self.spatial_encoder = PixelSetEncoder(
            input_dim,
            mlp1=mlp1,
            pooling=pooling,
            mlp2=mlp2,
            with_extra=with_extra,
            extra_size=extra_size,
        )
        self.temporal_encoder = LTAE(
            in_channels=mlp2[-1],
            n_head=n_head,
            d_k=d_k,
            d_model=d_model,
            n_neurons=mlp3,
            dropout=dropout,
            T=T,
            max_temporal_shift=max_temporal_shift,
        )
        self.decoder = get_decoder(mlp4, num_classes)

    def forward(self, pixels, mask, positions, extra, return_feats=False):
        """
        Args:
           input(tuple): (Pixel-Set, Pixel-Mask) or ((Pixel-Set, Pixel-Mask), Extra-features)
           Pixel-Set : Batch_size x Sequence length x Channel x Number of pixels
           Pixel-Mask : Batch_size x Sequence length x Number of pixels
           Positions : Batch_size x Sequence length
           Extra-features : Batch_size x Sequence length x Number of features
        """
        spatial_feats = self.spatial_encoder(pixels, mask, extra)
        temporal_feats = self.temporal_encoder(spatial_feats, positions)
        logits = self.decoder(temporal_feats)
        if return_feats:
            return logits, temporal_feats
        else:
            return logits

    def forward_with_head_evidence(
        self, pixels, mask, positions, extra, top_fraction=0.30,
        coverage=0.75, min_observations=3, min_outside=2,
        structure='interval', intervention='mean', gate=0.5,
    ):
        """Ordinary logits plus deterministic head-local masked logits.

        The usual classification path retains its train-mode BatchNorm and
        Dropout. A separate comparison through the existing temporal MLP and
        classifier uses running BN statistics for both original and masked
        head outputs, keeping the contribution difference meaningful.
        """
        spatial_feats = self.spatial_encoder(pixels, mask, extra)
        temporal_feats, attention, values = self.temporal_encoder(
            spatial_feats, positions, return_head_parts=True
        )
        logits = self.decoder(temporal_feats)
        if structure == 'top30':
            inside, valid = select_attention_top_fraction(attention, positions, top_fraction)
        elif structure == 'interval':
            inside, valid = select_attention_intervals(
                attention, positions, top_fraction=top_fraction,
                coverage=coverage, min_observations=min_observations,
                min_outside=min_outside,
            )
        else:
            raise ValueError(f'Unknown evidence structure: {structure}')
        counterfactuals = build_counterfactual_head_embeddings(
            attention, values, inside, intervention=intervention, gate=gate,
        )
        batch, cases, channels = counterfactuals.shape
        with frozen_evidence_normalization(
            self.temporal_encoder.mlp, self.decoder,
        ):
            evidence_features = self.temporal_encoder.mlp(
                counterfactuals.reshape(batch * cases, channels)
            )
            evidence_logits = self.decoder(evidence_features).reshape(
                batch, cases, -1
            )
        return logits, evidence_logits, valid

    def forward_m1(self, pixels, mask, positions, extra, tau=.5, rho=.5):
        """One PSE pass, ordinary Full path plus jointly retained Soft Top50 heads.

        No model parameters are added. Only Keep's BatchNorm uses frozen running
        statistics; its shared weights keep gradients and Dropout stays active.
        """
        import torch
        from utils.soft_top50 import frozen_batchnorm_only, keep_head_embeddings, soft_top50
        valid_time = mask.bool().any(-1)
        if not valid_time.any(-1).all():
            raise ValueError('M1 requires at least one observed date per sample')
        if bool(valid_time.all()):
            spatial = self.spatial_encoder(pixels, mask, extra)
            attention_mask = None  # Preserve the original numerical path exactly.
        else:
            selected_extra = None if extra is None else extra[:, None].expand(-1, pixels.size(1), -1)[valid_time]
            selected = self.spatial_encoder(pixels[valid_time][:, None], mask[valid_time][:, None], selected_extra)
            spatial = selected.new_zeros(pixels.size(0), pixels.size(1), selected.size(-1))
            spatial[valid_time] = selected[:, 0]
            attention_mask = valid_time
        temporal, attention, values, scores = self.temporal_encoder(
            spatial, positions, return_attention_scores=True, valid_time=attention_mask)
        full = self.decoder(temporal)
        info = soft_top50(scores, valid_time, tau=tau, rho=rho)
        pooled, normalized, mass = keep_head_embeddings(attention, values, info['selection'])
        with frozen_batchnorm_only(self.temporal_encoder.mlp, self.decoder):
            keep_temporal = self.temporal_encoder.dropout(self.temporal_encoder.mlp(pooled))
            keep = self.decoder(keep_temporal)
        info.update(attention=attention, keep_attention=normalized, retained_mass=mass, scores=scores)
        return full, keep, info

    def param_ratio(self):
        total = get_ntrainparams(self)
        s = get_ntrainparams(self.spatial_encoder)
        t = get_ntrainparams(self.temporal_encoder)
        c = get_ntrainparams(self.decoder)

        print("TOTAL TRAINABLE PARAMETERS : {}".format(total))
        print(
            "RATIOS: Spatial {:5.1f}% , Temporal {:5.1f}% , Classifier {:5.1f}%".format(
                s / total * 100, t / total * 100, c / total * 100
            )
        )

        return total


